import type { ScanRecord } from '../types';

/** Serialize scans as pretty JSON. */
export function toJsonExport(records: ScanRecord[]): string {
  return JSON.stringify(
    {
      app: 'VisionGuard AI',
      exportedAt: new Date().toISOString(),
      count: records.length,
      scans: records,
    },
    null,
    2,
  );
}

const CSV_HEADERS = [
  'id',
  'timestamp',
  'iso_date',
  'label',
  'confidence',
  'association',
  'model',
  'source',
  'summary',
  'bookmarked',
  'notes',
] as const;

function csvEscape(value: string): string {
  if (/[",\n\r]/.test(value)) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

/** Serialize scans as CSV (RFC 4180-style escaping). */
export function toCsvExport(records: ScanRecord[]): string {
  const lines: string[] = [CSV_HEADERS.join(',')];
  for (const r of records) {
    lines.push(
      [
        r.id,
        String(r.timestamp),
        new Date(r.timestamp).toISOString(),
        r.label,
        r.confidence == null ? '' : r.confidence.toFixed(4),
        r.associationState,
        r.modelId,
        r.sourceType,
        r.summary,
        r.bookmarked ? 'true' : 'false',
        r.notes,
      ]
        .map(csvEscape)
        .join(','),
    );
  }
  return lines.join('\r\n');
}

/** Trigger a browser download of a text file. */
export function downloadTextFile(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

/** Build a printable HTML report for one scan (opened in a new window). */
export function buildPrintableReport(record: ScanRecord): string {
  const esc = (s: string) =>
    s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8" />
<title>VisionGuard report — ${esc(record.label)}</title>
<style>
  body { font-family: Georgia, serif; color: #111; margin: 2rem; }
  h1 { font-size: 1.4rem; }
  dl { display: grid; grid-template-columns: 12rem 1fr; gap: .35rem 1rem; }
  dt { font-weight: bold; }
  .snap { max-width: 420px; border: 1px solid #ccc; margin-top: 1rem; }
  .foot { margin-top: 2rem; font-size: .8rem; color: #555; }
</style></head>
<body>
  <h1>VisionGuard AI — Object Report</h1>
  <dl>
    <dt>Object</dt><dd>${esc(record.label)}</dd>
    <dt>Detected</dt><dd>${esc(new Date(record.timestamp).toLocaleString())}</dd>
    <dt>Confidence</dt><dd>${record.confidence == null ? 'n/a' : (record.confidence * 100).toFixed(1) + '%'}</dd>
    <dt>Hand association</dt><dd>${esc(record.associationState)}</dd>
    <dt>Model</dt><dd>${esc(record.modelId)}</dd>
    <dt>Source</dt><dd>${esc(record.sourceType)}</dd>
    <dt>Notes</dt><dd>${esc(record.notes || '—')}</dd>
  </dl>
  <h2>Description</h2>
  <p style="white-space: pre-wrap">${esc(record.summary)}</p>
  ${record.snapshotDataUrl ? `<img class="snap" src="${record.snapshotDataUrl}" alt="Snapshot of ${esc(record.label)}" />` : ''}
  <p class="foot">Generated by VisionGuard AI. Detection is model-based estimation, not a verified identification. Descriptions are informational and not safety advice.</p>
  <script>window.addEventListener('load', () => setTimeout(() => window.print(), 250));</script>
</body></html>`;
}

export function openPrintableReport(record: ScanRecord): void {
  const win = window.open('', '_blank', 'noopener,noreferrer');
  if (!win) return;
  win.document.write(buildPrintableReport(record));
  win.document.close();
}
